"""Write the terminal × fact matrix into README.md, from terminals.toml.

    python tools/matrix.py          # rewrite the matrix in README.md
    python tools/matrix.py --check  # fail if README.md is out of date (CI)
"""

from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

import terminal_facts as tf  # noqa: E402

BEGIN, END = "<!-- BEGIN MATRIX -->", "<!-- END MATRIX -->"


def heading(rows: list[tf.Row], row: tf.Row) -> str:
    if row.extends is None:
        return row.name
    by_id = {each.id: each for each in rows}
    base = row
    while base.extends:
        base = by_id[base.extends]
    parts = []
    if "version_min" in row.match:
        parts.append(f"≥ {row.match['version_min']}")
    if "version_max" in row.match:
        parts.append(f"≤ {row.match['version_max']}")
    if "os" in row.match:
        names = {"macos": "macOS", "linux": "Linux", "windows": "Windows", "bsd": "BSD"}
        parts.append("(" + ", ".join(names[each] for each in row.match["os"]) + ")")
    return f"{base.name} {' '.join(parts)}"


def cell(value) -> str:
    if value is None:
        return "?"
    if value is True:
        return "yes"
    if value is False:
        return "**no**"
    if isinstance(value, int):
        for unit, size in (("MiB", 1048576), ("MB", 1000000), ("KiB", 1024), ("kB", 1000)):
            if value % size == 0:
                return f"{value // size} {unit}"
        return f"{value} bytes"
    return f"`{value}`"


def matrix(rows: list[tf.Row]) -> str:
    lines = ["| Fact | " + " | ".join(heading(rows, row) for row in rows) + " |"]
    lines.append("|---|" + "---|" * len(rows))
    resolved = [tf.resolved_facts(rows, row.id) for row in rows]
    for key in tf.FACTS:
        lines.append(f"| `{key}` | " + " | ".join(cell(facts.get(key)) for facts in resolved) + " |")
    lines.append("")
    lines.append("`?` unknown (probe). Each fact's evidence is next to it in `terminals.toml`.")
    lines.append("*Generated by `tools/matrix.py`; don't edit by hand.*")
    return "\n".join(lines)


def main() -> None:
    readme = ROOT / "README.md"
    text = readme.read_text()
    start, end = text.index(BEGIN) + len(BEGIN), text.index(END)
    updated = text[:start] + "\n\n" + matrix(tf.load()) + "\n\n" + text[end:]
    if "--check" in sys.argv:
        if updated != text:
            sys.exit("README.md matrix is out of date: run python tools/matrix.py")
        print("README.md matrix is up to date")
    else:
        readme.write_text(updated)


if __name__ == "__main__":
    main()
